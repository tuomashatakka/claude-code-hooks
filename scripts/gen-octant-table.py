#!/usr/bin/env python3
"""Generate packages/image-to-ascii/src/glyphs/octant-table.ts.

The mapping is taken from the Unicode character names (BLOCK OCTANT-<positions>)
rather than from the block's ascending-order arithmetic, so the 26 masks that
Unicode serves from pre-existing characters cannot be silently mis-derived.

Usage:
    python3 scripts/gen-octant-table.py > packages/image-to-ascii/src/glyphs/octant-table.ts

Requires a Python whose unicodedata is Unicode 16.0 or newer (3.13+).
"""
import sys
import unicodedata as u

if u.unidata_version < '16.0.0':
    sys.exit(f'need unicodedata >= 16.0.0, have {u.unidata_version}')

# 230 of the 256 masks live in one contiguous ascending run.
by_mask: dict[int, int] = {}
for cp in range(0x1CD00, 0x1CDE6):
    name = u.name(chr(cp))
    assert name.startswith('BLOCK OCTANT-'), name
    by_mask[sum(1 << (int(d) - 1) for d in name.split('-')[1])] = cp
assert len(by_mask) == 230, len(by_mask)

# The other 26 already had characters before Unicode 16. Six of them sit outside
# the octant block entirely — missing those is the bug kitty shipped (#9849).
FILLERS = {
    0x00: 0x0020, 0x01: 0x1CEA8, 0x02: 0x1CEAB, 0x03: 0x1FB82, 0x05: 0x2598,
    0x0A: 0x259D, 0x0F: 0x2580, 0x14: 0x1FBE6, 0x28: 0x1FBE7, 0x3F: 0x1FB85,
    0x40: 0x1CEA3, 0x50: 0x2596, 0x55: 0x258C, 0x5A: 0x259E, 0x5F: 0x259B,
    0x80: 0x1CEA0, 0xA0: 0x2597, 0xA5: 0x259A, 0xAA: 0x2590, 0xAF: 0x259C,
    0xC0: 0x2582, 0xF0: 0x2584, 0xF5: 0x2599, 0xFA: 0x259F, 0xFC: 0x2586,
    0xFF: 0x2588,
}
OUT_OF_RANGE = {0x1CEA0, 0x1CEA3, 0x1CEA8, 0x1CEAB, 0x1FBE6, 0x1FBE7}

gaps = set(range(256)) - set(by_mask)
assert set(FILLERS) == gaps, f'filler set does not match the gaps: {sorted(gaps ^ set(FILLERS))}'
for cp in FILLERS.values():
    u.name(chr(cp))  # raises for an unassigned code point

skips = sorted(FILLERS)
for mask, cp in by_mask.items():
    expected = 0x1CD00 + mask - sum(1 for s in skips if s < mask)
    assert cp == expected, f'mask {mask:#04x}: {cp:#x} != {expected:#x}'

by_mask.update(FILLERS)
assert len(by_mask) == 256

chars = [chr(by_mask[m]) for m in range(256)]
out_of_range = sorted(m for m, cp in FILLERS.items() if cp in OUT_OF_RANGE)

print('// GENERATED by scripts/gen-octant-table.py — do not edit by hand.')
print('//')
print('// Block octants divide a cell into a 2x4 grid; bit i of the mask selects')
print('// sub-cell i+1 in row-major order, the same numbering the sextants use:')
print('//')
print('//     1 2      bit0 bit1')
print('//     3 4      bit2 bit3')
print('//     5 6      bit4 bit5')
print('//     7 8      bit6 bit7')
print('//')
print('// U+1CD00..U+1CDE5 holds 230 masks in ascending order. The remaining 26')
print('// already had characters, and six of those sit OUTSIDE that run:')
print('// U+1CEA0, U+1CEA3, U+1CEA8, U+1CEAB (Unicode 16) plus U+1FBE6, U+1FBE7.')
print('// Deriving the run arithmetically and letting those six fall through to the')
print('// font is exactly the bug kitty shipped (kovidgoyal/kitty#9849), so the whole')
print('// table is materialised and re-checked against the Unicode names in tests.')
print()
print('/** Character for each 2x4 mask, indexed by mask. */')
print('export const OCTANT_CHARS: readonly string[] = [')
for i in range(0, 256, 8):
    row = ', '.join(f"'{c}'" for c in chars[i:i + 8])
    print(f'  {row},')
print('];')
print()
print('/** Masks drawn by a character from outside the U+1CD00 run. */')
print('export const OCTANT_OUT_OF_RANGE: readonly number[] = [')
print('  ' + ', '.join(f'0x{m:02x}' for m in out_of_range) + ',')
print('];')
